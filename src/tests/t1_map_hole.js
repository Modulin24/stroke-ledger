/* Mapping a hole: tee, green outline, undo, drag, facts, next hole; then the course row and the map file. */
const { start } = require('./harness');
const TEE = [18.4370, -69.9905], G = [[18.44000, -69.99000], [18.44010, -69.98985], [18.44025, -69.98990], [18.44028, -69.99008], [18.44012, -69.99015], [18.44003, -69.99010]];
(async () => {
  const t = await start({ geo: { latitude: TEE[0], longitude: TEE[1], accuracy: 5 } }), p = t.page;
  await t.open('courses');
  t.ok((await t.text('.maprow')).includes('Not on the map yet'), 'course starts unmapped');
  await p.click('.maprow button');
  await t.mapReady();
  t.ok((await t.text('.holehead h2')).trim().toUpperCase() === 'HOLE 1', 'editor opens on hole 1');
  t.ok(await p.locator('.seg button[aria-pressed=true]').innerText() === 'Tee', 'tee tool first');
  const c0 = await p.evaluate(() => { const c = SLMap._map().getCenter(); return [c.lat, c.lng]; });
  t.ok(Math.abs(c0[0] - 18.43733) < 0.002 && Math.abs(c0[1] + 69.99003) < 0.002, 'map opens over the club', c0);
  t.ok(t.state.styles === 1 && t.state.tilemaps >= 4, 'photo style and sharpness probe requested', [t.state.styles, t.state.tilemaps]);
  t.ok(await p.evaluate(() => SLMap.photo.state === 'ok' && SLMap.photo.max === 19), 'photo capped at the sharpest level that exists (19)');
  await t.jump(TEE, 18);
  await t.tapMap(TEE);
  let d = await t.data(), geo = d.courses.list[0].holes[0].geo;
  t.ok(geo && Math.abs(geo.t[0] - TEE[0]) < 2e-5 && Math.abs(geo.t[1] - TEE[1]) < 2e-5 && geo.u === 1, 'tee saved where tapped', geo);
  t.ok((await p.locator('.seg button[aria-pressed=true]').innerText()).startsWith('Green edge'), 'tool moves on to the green');
  await t.jump([18.44014, -69.99000], 19.1);
  for (const i of [3, 0, 4, 2, 1]) await t.tapMap(G[i]);          // out of order on purpose
  d = await t.data(); geo = d.courses.list[0].holes[0].geo;
  t.ok(geo.g.length === 5, 'five green points saved', geo.g.length);
  const conv = await p.evaluate(g => { const P = g.map(q => SLMap.toXY(g[0], q)); let s = 0; for (let i = 0; i < P.length; i++) { const a = P[i], b = P[(i + 1) % P.length], c = P[(i + 2) % P.length]; const z = (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0]); s += Math.sign(z); } return Math.abs(s); }, geo.g);
  t.ok(conv === 5, 'points were put in order around the green (no crossing edges)', conv);
  const facts = await t.text('.note');
  t.ok(/green measures about \d+ yds deep and \d+ wide/.test(facts) && /is 38\d yds in a straight line; the card says \d+/.test(facts), 'facts line shows green size and tee-to-green distance', facts);
  await t.tapMap(G[5]);
  t.ok((await t.data()).courses.list[0].holes[0].geo.g.length === 6, 'sixth point added');
  await p.click('button[data-act=mapUndo]');
  t.ok((await t.data()).courses.list[0].holes[0].geo.g.length === 5, 'undo removes it');
  const before = (await t.data()).courses.list[0].holes[0].geo.g.map(q => q.join());
  await t.dragMarker('.mk-v', [18.44019, -69.99017]);
  const after = (await t.data()).courses.list[0].holes[0].geo.g.map(q => q.join());
  t.ok(after.length === 5 && after.filter(q => !before.includes(q)).length === 1, 'dragging a dot moves one point', [before, after]);
  await p.click('button[data-act=mapUndo]');
  t.ok(JSON.stringify((await t.data()).courses.list[0].holes[0].geo.g.map(q => q.join())) === JSON.stringify(before), 'undo puts the dragged point back');
  await t.shot('t1-editor-green');
  await p.click('button[data-act=mapView][data-v=hole]');
  await t.shot('t1-editor-hole');
  // GPS button for the next hole's tee
  await p.click('.btnrow .btn.flag');
  t.ok((await t.text('.holehead h2')).trim().toUpperCase() === 'HOLE 2', 'Next hole moves to hole 2');
  const c1 = await p.evaluate(() => { const c = SLMap._map().getCenter(); return [c.lat, c.lng]; });
  t.ok(Math.abs(c1[0] - 18.44014) < 0.0006, 'hole 2 opens beside the green of hole 1', c1);
  await t.geo([18.4405, -69.9895], 6);
  await p.click('button[data-act=mapHere][data-v=tee]');
  await p.waitForFunction(() => { const d = JSON.parse(localStorage.getItem('strokeLedger.v1')); const g = d.courses.list[0].holes[1].geo; return g && g.t; }, null, { timeout: 12000 });
  d = await t.data();
  t.ok(Math.abs(d.courses.list[0].holes[1].geo.t[0] - 18.4405) < 1e-5, 'Tee is where I stand uses the GPS position', d.courses.list[0].holes[1].geo);
  await t.geo([18.4432, -69.9893], 6);
  await p.waitForTimeout(400);
  await p.click('button[data-act=mapHere][data-v=green]');
  await p.waitForFunction(() => { const d = JSON.parse(localStorage.getItem('strokeLedger.v1')); const g = d.courses.list[0].holes[1].geo; return g && g.g && g.g.length >= 8; }, null, { timeout: 12000 });
  d = await t.data();
  const rad = await p.evaluate(g => g.map(q => SLMap.dist([18.4432, -69.9893], q)), d.courses.list[0].holes[1].geo.g);
  t.ok(rad.every(r => Math.abs(r - 13) < 0.3), 'Green is where I stand draws a 13-yard circle', rad.map(r => +r.toFixed(1)));
  await p.click('button[data-act=mapEdClose]');
  t.ok((await t.text('.maprow')).includes('2 of 9 holes on the map'), 'course row counts mapped holes', await t.text('.maprow'));
  // the map file: save, wipe, load
  await p.click('#setupBtn');
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('button[data-act=saveMapFile]')]);
  const file = require('path').join(__dirname, 'out', 'map-file.json'); await dl.saveAs(file);
  const mf = JSON.parse(require('fs').readFileSync(file, 'utf8'));
  t.ok(mf.app === 'stroke-ledger-map' && mf.courses.length === 1 && mf.courses[0].id === 'sdcc-caobas' && mf.courses[0].holes.filter(Boolean).length === 2, 'map file holds the two mapped holes', mf.courses.map(c => [c.id, c.holes.filter(Boolean).length]));
  await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForSelector('#tabs button'); await p.click('#setupBtn');
  t.ok((await t.text('#view')).includes('0 holes are on the map'), 'fresh start has no mapped holes');
  await p.setInputFiles('#map-file', file);
  await p.waitForFunction(() => /Loaded 2 holes on 1 course/.test((document.querySelector('#mapFileMsg') || {}).textContent || ''), null, { timeout: 5000 });
  d = await t.data();
  t.ok(d.courses.list[0].holes[0].geo.g.length === 5 && d.courses.list[0].holes[1].geo.g.length === 10, 'loading the map file restores both holes');
  await t.end();
})().catch(e => { console.error(e); process.exit(1); });
