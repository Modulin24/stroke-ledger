/* Playing a hole with the map: distances, GPS, aim and pattern, marking shots by GPS and by tap, the flag, undo. */
const { start } = require('./harness');
const TEE = [18.4370, -69.9905], G = [[18.44000, -69.99000], [18.44010, -69.98985], [18.44025, -69.98990], [18.44028, -69.99008], [18.44012, -69.99015]];
const near = (a, b, tol) => Math.abs(a - b) <= tol;
(async () => {
  const t = await start({ geo: { latitude: TEE[0], longitude: TEE[1], accuracy: 4 } }), p = t.page;
  await t.open();
  t.ok((await t.text('#view')).includes('Put this app on your Home Screen'), 'iPhone Safari gets the Home Screen hint');
  await p.click('button[data-act=hintOff]');
  t.ok(!(await t.text('#view')).includes('Put this app on your Home Screen'), 'hint can be dismissed');
  await p.evaluate(([tee, g]) => { const d = JSON.parse(localStorage.getItem('strokeLedger.v1')); d.courses.list[0].holes[0].geo = { t: tee, g, u: 1 }; localStorage.setItem('strokeLedger.v1', JSON.stringify(d)); }, [TEE, G]);
  await p.reload(); await p.waitForSelector('#tabs button');
  await p.click('form[data-sub=newRound] button[type=submit]');
  await t.mapReady();
  const calc = await p.evaluate(([tee, g]) => { const c = SLMap.centroid(g), f = SLMap.fcb(tee, g); return { c, brg: SLMap.bearing(tee, c), f: f.f, cc: f.c, b: f.b }; }, [TEE, G]);
  let fcb = await t.text('#fcb');
  t.ok(/Front\s*371\s*Centre\s*387\s*Back\s*401/i.test(fcb.replace(/\n/g, ' ')) && /from the tee/.test(fcb), 'front, centre and back from the tee before GPS is on', fcb);
  const brg = await p.evaluate(() => SLMap._map().getBearing());
  t.ok(near(((brg % 360) + 360) % 360, calc.brg, 0.6), 'photo is turned so the hole runs up the screen', [brg, calc.brg]);
  t.ok((await t.text('#gpsBar')).includes('GPS off'), 'GPS starts off');
  await t.shot('t2-1-tee');
  await p.click('#gpsBar button');
  await p.waitForFunction(() => /±/.test(document.querySelector('#gpsBar').textContent), null, { timeout: 8000 });
  t.ok(/from you/.test(await t.text('#fcb')), 'with GPS on, distances are from you', await t.text('#fcb'));
  t.ok(await p.locator('.mk-me').count() === 1, 'blue dot shown');
  // aim: driver pattern down the hole
  await p.click('button[data-act=aimToggle]');
  let aim = await t.text('.aimbar');
  t.ok(/Driver aimed 250 yds away, leaving 13\d to the flag/.test(aim) && /Pattern: ± 2\d yds left-right/.test(aim), 'tee-shot aim: driver, 250 out, pattern size', aim);
  t.ok(await p.locator('.mk-aim').count() === 1, 'aim cross on the map');
  const pat = await p.evaluate(async () => (await SLMap._map().getSource('sl-pat').getData()).features.map(f => f.properties.k));
  t.ok(JSON.stringify(pat) === '[2,1]', 'two rings drawn (nearly all, and 2 in 3)', pat);
  await t.shot('t2-2-aim-tee');
  const aimTo = await p.evaluate(([tee, brg]) => SLMap.dest(SLMap.dest(tee, brg, 235), brg - 90, 18), [TEE, calc.brg]);
  await t.dragMarker('.mk-aim', aimTo);
  aim = await t.text('.aimbar');
  t.ok(/Driver aimed 23\d yds away/.test(aim) && (await p.locator('button[data-act=aimBest]').count()) === 1, 'dragging the cross moves the aim and offers a reset', aim);
  await p.click('button[data-act=aimSave]');
  let d = await t.data(), plan = d.courses.list[0].holes[0].plan;
  t.ok(plan.club === 'D' && Array.isArray(plan.ag) && near(plan.ag[0], aimTo[0], 3e-5), 'aim saved to the hole plan', plan);
  await p.click('button[data-act=aimToggle]');
  t.ok(await p.locator('.aimbar').count() === 0 && await p.locator('.mk-plan').count() === 1, 'aim off; saved plan aim stays as a small target');
  // too far away: GPS refuses to mark
  await t.geo([18.50, -69.90], 5); await p.waitForTimeout(300);
  await p.click('button[data-act=markBall]');
  await p.waitForFunction(() => /from this green/.test(document.querySelector('#markMsg').textContent), null, { timeout: 12000 });
  t.ok(/miles from this green/.test(await t.text('#markMsg')), 'GPS far from the hole is refused', await t.text('#markMsg'));
  // drive: walk 245 yards down the line and mark
  const ball1 = await p.evaluate(([tee, brg]) => SLMap.r6(SLMap.dest(tee, brg, 245)), [TEE, calc.brg]);
  await t.geo(ball1, 4); await p.waitForTimeout(400);
  await p.click('button[data-act=markBall]');
  await p.waitForFunction(() => /Pin dropped/.test(document.querySelector('#markMsg').textContent), null, { timeout: 12000 });
  t.ok(/Pin dropped 142 yards from the flag/.test(await t.text('#markMsg')) && await p.inputValue('#pad-d') === '142', 'Mark ball here fills in 142 yards left', [await t.text('#markMsg'), await p.inputValue('#pad-d')]);
  await p.click('button[data-act=padClub][data-v=D]');
  t.ok(await p.locator('button[data-act=padLie][data-v=fwy]').getAttribute('aria-pressed') === 'true', 'lie stays on fairway');
  await t.shot('t2-3-marked');
  await p.click('form[data-sub=addShot] button[type=submit]');
  d = await t.data(); let h = Object.values(d.rounds).find(r => !r.example).holes[0];
  t.ok(h.shots.length === 1 && h.shots[0].c === 'D' && h.shots[0].lie === 'tee' && h.shots[0].d === 391 && h.next.lie === 'fwy' && h.next.d === 142 && near(h.next.g[0], ball1[0], 1e-5), 'shot 1 saved with its finish position', h);
  t.ok(/about 245 yd shot/.test(await t.text('.shots')), 'shot row shows the measured drive', await t.text('.shots'));
  fcb = await t.text('#fcb');
  t.ok(/Centre\s*142/i.test(fcb.replace(/\n/g, ' ')), 'distances update for the second shot', fcb);
  // approach: best aim, then move the flag
  await p.click('button[data-act=aimToggle]');
  aim = await t.text('.aimbar');
  const m1 = /(\d+)% of your shots finish on the green from this aim/.exec(aim);
  t.ok(m1 && +m1[1] > 40 && +m1[1] < 100 && /iron|PW|hybrid/i.test(aim), 'approach aim reports the share of shots on the green', aim);
  await t.shot('t2-4-aim-approach');
  await p.click('button[data-act=aimToggle]');
  await p.click('button[data-act=mapView][data-v=green]');
  const pin = [18.440215, -69.989945];
  await t.dragMarker('.mk-flag', pin);
  d = await t.data(); h = Object.values(d.rounds).find(r => !r.example).holes[0];
  t.ok(h.pin && near(h.pin[0], pin[0] , 6e-5) && near(h.pin[1], pin[1], 6e-5), "today's flag saved on the round", h.pin);
  t.ok(/Flag\s*1[45]\d/i.test((await t.text('#fcb')).replace(/\n/g, ' ')), 'a Flag distance appears', await t.text('#fcb'));
  await p.click('button[data-act=aimToggle]');
  aim = await t.text('.aimbar');
  const best = await p.evaluate(async () => { const f = (await SLMap._map().getSource('sl-aim').getData()).features[0].geometry.coordinates[1]; return [f[1], f[0]]; });
  const off = await p.evaluate(([a, b, g]) => [SLMap.dist(a, b), SLMap.inPoly(a, g)], [best, h.pin, G]);
  t.ok(off[1] && off[0] > 1.5 && /saves 0\.\d\d strokes a shot over aiming at the flag/.test(aim), 'with a tucked flag the best aim sits away from it, inside the green', [off, aim]);
  await t.shot('t2-5-aim-tucked');
  await p.click('button[data-act=aimToggle]');
  // approach finishes on the green: tap the photo
  const ball2 = [18.44012, -69.99003];
  await t.tapMap(ball2);
  t.ok(await p.locator('button[data-act=padLie][data-v=grn]').getAttribute('aria-pressed') === 'true' && await p.inputValue('#pad-d') === '' && /on the green, about \d+ feet/.test(await t.text('#markMsg')), 'a tap inside the outline switches the lie to Green and asks for feet', await t.text('#markMsg'));
  await p.click('form[data-sub=addShot] button[type=submit]');
  t.ok(/Enter how far/.test(await t.text('.err')), 'feet are required on the green');
  await p.fill('#pad-d', '20'); await p.click('button[data-act=padClub][data-v="8i"]');
  await p.click('form[data-sub=addShot] button[type=submit]');
  await p.fill('#pad-d', '2'); await p.click('form[data-sub=addShot] button[type=submit]');
  await p.click('button[data-act=holed]');
  d = await t.data(); h = Object.values(d.rounds).find(r => !r.example).holes[0];
  t.ok(h.done && h.shots.length === 4 && h.shots[1].g && h.shots[2].g && h.shots[2].lie === 'grn' && h.shots[2].d === 20 && !h.next, 'hole finished in 4 with positions on shots 2 and 3', h.shots);
  const rows = await t.text('.shots');
  t.ok(/\n1[34]\d yd shot/.test(rows) && (rows.match(/yd shot/g) || []).length === 2, 'approach distance shown; putts carry no GPS distance', rows);
  const model = await p.evaluate(async () => ({ lines: (await SLMap._map().getSource('sl-path').getData()).features.map(f => f.geometry.coordinates.length), dots: document.querySelectorAll('.mk-dot').length, flagDrag: !!document.querySelector('.mk-flag') }));
  t.ok(model.lines.length === 1 && model.lines[0] === 4 && model.dots === 2, 'finished hole draws tee, two shot pins and the flag as one line', model);
  await p.click('button[data-act=mapView][data-v=hole]');
  await t.shot('t2-6-done', true);
  const sg = await p.locator('.holed .sgc').innerText();
  t.ok(/^[+−]?\d\.\d\d$/.test(sg.trim()), 'hole shows strokes gained', sg);
  // undo back to the fairway keeps the pin
  await p.click('button[data-act=reopen]'); await p.click('button[data-act=undoShot]'); await p.click('button[data-act=undoShot]');
  d = await t.data(); h = Object.values(d.rounds).find(r => !r.example).holes[0];
  t.ok(h.shots.length === 1 && h.next.lie === 'fwy' && h.next.d === 142 && near(h.next.g[0], ball1[0], 1e-5), 'undo returns the ball to the marked fairway spot', h.next);
  await p.click('button[data-act=undoShot]');
  d = await t.data(); h = Object.values(d.rounds).find(r => !r.example).holes[0];
  t.ok(h.shots.length === 0 && h.next.lie === 'tee' && !h.next.g, 'undoing the drive returns to the tee');
  // mark the tee, then hole 2 has no map
  await t.geo(TEE, 4); await p.waitForTimeout(400);
  await p.click('button[data-act=markTee]');
  await p.waitForSelector('button[data-act=resetTee]', { timeout: 12000 });
  d = await t.data(); h = Object.values(d.rounds).find(r => !r.example).holes[0];
  t.ok(h.tg && near(h.tg[0], TEE[0], 1e-5), 'tee position recorded for the round', h.tg);
  await p.click('button[data-act=hole][data-i="1"]');
  t.ok((await t.text('.maphint')).includes('Hole 2 is not on the map yet') && await p.locator('#mapSlot').count() === 0, 'an unmapped hole offers mapping instead of a map');
  await p.click('.maphint button'); await t.mapReady();
  t.ok((await t.text('.rhead')).includes('Back to the round') && (await t.text('.holehead h2')).trim().toUpperCase() === 'HOLE 2', 'Map this hole opens the editor on that hole');
  await p.click('button[data-act=mapEdClose]');
  t.ok((await t.text('.holehead h2')).trim().toUpperCase() === 'HOLE 2' && await p.locator('form[data-sub=addShot]').count() === 1, 'and returns to the round');
  t.ok(t.state.badTiles === 0, 'never asked for photo tiles sharper than exist', t.state.badTiles);
  await t.end();
})().catch(e => { console.error(e); process.exit(1); });
